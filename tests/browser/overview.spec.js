import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

test('Overview derives status and preserves record context', async ({page}, info) => {
  await page.goto('/');
  await expect(page.locator('#page-heading')).toHaveText('Workspace');
  const overview = () => page.locator('.navigation-top').getByRole('link', {name:'Workspace overview', exact:true}).click();
  const group = title => page.getByRole('region', {name:'Review status'}).locator('section').filter({has:page.getByRole('heading',{name:title,exact:true})});
  for (const title of ['Failed saves','Pending saves','Other unsaved reviews']) await expect(group(title).locator('p')).toHaveText('None.');
  await page.locator('.page-directory').getByRole('link',{name:'Harbor morning',exact:true}).click();
  const note = page.getByRole('textbox',{name:'Review note',exact:true});
  await note.fill('Keep this draft');
  await page.getByRole('searchbox').fill('Market');
  await overview();
  await group('Other unsaved reviews').getByRole('link',{name:'Harbor morning: Review changes',exact:true}).click();
  await expect(page.locator('#review-heading')).toBeFocused();
  await expect(note).toHaveValue('Keep this draft');
  await expect(page.getByRole('searchbox')).toHaveValue('Market');
  await page.goBack(); await expect(page.locator('#page-heading')).toHaveText('Workspace');
  await page.goForward(); await expect(note).toHaveValue('Keep this draft');
  await page.getByRole('button',{name:'Save review',exact:true}).click();
  await note.fill('Newer draft');
  await overview();
  await expect(group('Pending saves')).toContainText('Saving earlier edits; newer changes are not saved.');
  await group('Pending saves').getByRole('link').click();
  const simulate = async name => {
    const summary = page.locator('summary').filter({hasText:/^Demo save controls$/});
    if (!await summary.evaluate(el=>el.parentElement.open)) await summary.click();
    await page.getByRole('button',{name,exact:true}).click();
  };
  await simulate('Fail save');
  await overview();
  await expect(group('Pending saves')).toContainText('None.');
  await expect(group('Failed saves')).toContainText('Harbor morning');
  await mkdir('output/playwright/overviews',{recursive:true});
  await page.screenshot({path:`output/playwright/overviews/${info.project.name}.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>document.documentElement.style.fontSize='200%');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`output/playwright/overviews/${info.project.name}-narrow.png`,fullPage:true});
  await group('Failed saves').getByRole('link').click();
  await expect(note).toHaveValue('Newer draft');
  await page.getByRole('button',{name:'Save review',exact:true}).click();
  await simulate('Complete save');
  await overview();
  for (const title of ['Failed saves','Pending saves','Other unsaved reviews']) await expect(group(title)).toContainText('None.');
  await page.locator('.page-directory').getByRole('link',{name:'Harbor morning',exact:true}).click();
  await expect(page.locator('#save-feedback')).toHaveText('Saved in this demo.');
});
